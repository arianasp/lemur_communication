#Analysis of periods of joint movement

library(cocomo)

load('~/Dropbox/lemur_communication/Mapping vocal interactions in space and time differentiates signal broadcast versus signal exchange in meerkat groups/data/HM2017_COORDINATES_all_sessions_anon.RData')
speed_thresh <- 0.2

xs <- HM2017_allX
ys <- HM2017_allY

n_inds <- nrow(xs)
n_times <- ncol(xs)

heads <- moving <- matrix(NA, n_inds, n_times)
prox <- array(NA, c(n_inds, n_inds, n_times))

for(i in 1:n_inds){
  out <- cocomo::get_heading_and_speed_temporal(xs[i,],ys[i,],t_window = 10)
  heads[i,] <- out$heads
  moving[i,] <- out$speeds > speed_thresh
}

max_head_diff <- 0.2 # in radians

#---start function here--
n_inds <- nrow(heads)
n_times <- ncol(heads)

#calculate heading differences
head_diffs <- array(NA, c(n_inds, n_inds, n_times))
for(i in seq(1,(n_inds-1))){
  for(j in seq(i+1, n_inds)){
    headi <- heads[i,]
    headj <- heads[j,]
    angij <- headj - headi
    angij[which(angij< -pi)] <- angij[which(angij < -pi)] + 2*pi
    angij[which(angij > pi)] <- angij[which(angij > pi)] - 2*pi
    angij <- abs(angij)
    head_diffs[i,j,] <- angij
    head_diffs[j,i,] <- angij
  }
}

#matrix of whether two individuals are co-moving at a given time point
comove <- array(0, dim = c(n_inds, n_inds, n_times))
for(i in seq(1,(n_inds-1))){
  for(j in seq(i+1, n_inds)){
    comove[i,j,] <-  head_diffs[i,j,] < max_head_diff & moving[i,] & moving[j,]
    comove[j,i,] <-  head_diffs[i,j,] < max_head_diff & moving[i,] & moving[j,]
  }
}
comove[which(is.na(comove))] <- 0 #replace NAs with 0s for now - if missing data, you are not comoving

#get contiguous sequences of comoving between pairs
events <- data.frame()
for(i in seq(1,(n_inds-1))){
  for(j in seq(i+1, n_inds)){
    runs <- rle(comove[i,j,])
    stopIndex <- with(runs, cumsum(lengths)[values == 1])
    startIndex <- stopIndex - with(runs, lengths[values == 1]) + 1
    events_ij <- data.frame(i = i, j = j, t0 = startIndex, tf = stopIndex)
    events <- rbind(events, events_ij)
  }
}
seqs <- events

