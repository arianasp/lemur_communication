#Extract periods of co-movement and aggregate into events
#INPUTS:
# heads: n_inds x n_times matrix of headings (in radians)
# moving: n_inds x n_times matrix of whether the individual is moving (1) or not (0)
# max_head_diff: maximum angle between headings (in radians) to consider two individuals to be aligned in their movement
# min_comove_duration: minimum duration of comoving to count an individual as comoving (must be an odd integer)
# min_event_duration: minimum duration of an event
# verbose: boolean (T or F) whether to print comments while the function runs
#OUTPUT:
# agg_events: table of aggregated co-moving events, with columns:
#   $event_id: numeric value unique to the event
#   $start_time: start time (index) of each event
#   $stop_time: end time (index) of each event
#   $individuals: list of individuals involved in the event
get_comoves <- function(heads, moving, max_head_diff, min_comove_duration = 3, min_event_duration = 10, verbose = T){
  
  warning('This function was written quickly and partially by chatGPT during a hackathon - needs to be thoroughly checked!')
  
  #get number of individuals and time steps
  n_inds <- nrow(heads)
  n_times <- ncol(heads)
  
  #calculate heading differences between pairs of individuals
  head_diffs <- array(NA, c(n_inds, n_inds, n_times))
  for(i in seq(1,(n_inds-1))){
    for(j in seq(i+1, n_inds)){
      headi <- heads[i,]
      headj <- heads[j,]
      angij <- headj - headi
      angij[which(angij< -pi)] <- angij[which(angij < -pi)] + 2*pi
      angij[which(angij > pi)] <- angij[which(angij > pi)] - 2*pi
      angij <- abs(angij)
      head_diffs[i,j,] <- angij
      head_diffs[j,i,] <- angij
    }
  }
  
  if(verbose){
    print('calculating pairwise comove matrix')
  }
  
  #matrix of whether two individuals are co-moving at a given time point
  #this is defined as having a difference of headings less than or equal to max_head_diff AND both being moving in a given time point
  comove <- array(0, dim = c(n_inds, n_inds, n_times))
  for(i in seq(1,(n_inds-1))){
    for(j in seq(i+1, n_inds)){
      comove[i,j,] <-  head_diffs[i,j,] <= max_head_diff & moving[i,] & moving[j,]
      comove[j,i,] <-  head_diffs[i,j,] <= max_head_diff & moving[i,] & moving[j,]
    }
  }
  
  #replace NAs with 0s- if your data is missing, you cannot be involved in an event during that time period 
  comove[which(is.na(comove))] <- 0 
  
  #only count it as comoving if the individuals are comoving for at least min_comove_duration time steps 
  for(i in seq(1,(n_inds-1))){
    for(j in seq(i+1, n_inds)){
      curr <- comove[i,j,]
      filtered <- zoo::rollapply(curr, width = min_comove_duration, FUN = min, fill = 0)
      comove[i,j,] <- filtered
      comove[j,i,] <- filtered
    }
  }
  
  if(verbose){
    print('getting contiguous sequences of co-movement for each pair')
  }
  
  #get contiguous sequences of comoving between pairs
  seqs <- data.frame()
  for(i in seq(1,(n_inds-1))){
    for(j in seq(i+1, n_inds)){
      runs <- rle(comove[i,j,])
      stopIndex <- with(runs, cumsum(lengths)[values == 1])
      startIndex <- stopIndex - with(runs, lengths[values == 1]) + 1
      seqs_ij <- data.frame(i = i, j = j, t0 = startIndex, tf = stopIndex)
      seqs <- rbind(seqs, seqs_ij)
    }
  }
  
  #Helper function:
  #aggregate sequences that overlap in at least one individual and at least one time point
  #TODO: CHECK THIS CODE ESPECIALLY
  #code generated by chatGPT. Prompts:
  #I have a table of pairs of individuals (i and j) and time periods where they were together (t0 to tf) - call this "together sequences". I would like to aggregate these "together sequences" into events by combining together sequences that overlap in at least one individual and at least one time point. The output should be a table of events with start time, stop time, and which individuals were included in the event. Please generate R code to do this
  #This seems almost correct, but not quite. For example, if individual A and B are connected in time point 1 and then individual B and C are connected in time point 2, then these two events should also be aggregated into one event that includes all 3 individuals (A, B, and C) and runs from time 1 to 2. Can you update the code to incorporate this?
  aggregate_events <- function(seqs) {
    # Expected columns: i, j, t0, tf
    n <- nrow(seqs)
    
    if (n == 0) {
      return(data.frame(
        event_id = integer(),
        start_time = numeric(),
        stop_time = numeric(),
        individuals = I(list())
      ))
    }
    
    parent <- seq_len(n)
    
    find_root <- function(x) {
      while (parent[x] != x) {
        parent[x] <<- parent[parent[x]]
        x <- parent[x]
      }
      x
    }
    
    union <- function(a, b) {
      ra <- find_root(a)
      rb <- find_root(b)
      
      if (ra != rb) parent[rb] <<- ra
    }
    
    if (n > 1) {
      for (a in seq_len(n - 1)) {
        for (b in (a + 1):n) {
          
          # Share at least one individual
          shared_person <- length(intersect(
            c(seqs$i[a], seqs$j[a]),
            c(seqs$i[b], seqs$j[b])
          )) > 0
          
          # Overlap or consecutive time points
          time_connected <-
            seqs$t0[a] <= seqs$tf[b] + 1 &&
            seqs$t0[b] <= seqs$tf[a] + 1
          
          if (shared_person && time_connected) {
            union(a, b)
          }
        }
      }
    }
    
    component <- vapply(seq_len(n), find_root, integer(1))
    groups <- split(seq_len(n), component)
    
    events <- lapply(groups, function(idx) {
      list(
        start_time = min(seqs$t0[idx]),
        stop_time = max(seqs$tf[idx]),
        individuals = unique(c(seqs$i[idx], seqs$j[idx]))
      )
    })
    
    result <- data.frame(
      event_id = seq_along(events),
      start_time = vapply(events, `[[`, numeric(1), "start_time"),
      stop_time = vapply(events, `[[`, numeric(1), "stop_time")
    )
    
    result$individuals <- I(lapply(events, `[[`, "individuals"))
    
    result <- result[order(result$start_time), ]
    rownames(result) <- NULL
    
    return(result)
  }
  
  if(verbose){
    print('aggregating pairwise sequences into events')
  }
  
  #aggregate events
  agg_events <- aggregate_events(seqs)
  
  #remove short events (less than min_event_duration sec)
  agg_events_long <- agg_events[which((agg_events$stop_time - agg_events$start_time) >= min_event_duration),]
  
  if(verbose){
    print('done')
  }
  
  return(agg_events_long)
}

    